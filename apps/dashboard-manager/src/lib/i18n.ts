export type TKey = keyof (typeof DICT)['fr']

/** Read the operator's chosen locale from the `dm_lang` cookie (default fr). */
// Next 15 : `cookies()` est asynchrone, donc `getLang()` aussi (migration Next 15).
export async function getLang(): Promise<Lang> {
  const value = (await cookies()).get('dm_lang')?.value
  return value === 'en' ? 'en' : 'fr'
}

/** Bind a translator to a locale. `t('key')` returns the localized string. */
export function makeT(lang: Lang): (key: TKey) => string {
  const table = DICT[lang]
  return (key: TKey) => table[key] ?? DICT.fr[key] ?? String(key)
}
