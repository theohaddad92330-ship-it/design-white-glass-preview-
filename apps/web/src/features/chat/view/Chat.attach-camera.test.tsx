import { Chat } from './Chat'

beforeAll(() => {
  const proto = Element.prototype as unknown as Record<string, unknown>
  proto.hasPointerCapture ??= () => false
  proto.setPointerCapture ??= () => {}
  proto.releasePointerCapture ??= () => {}
})

/** Même faux `matchMedia` que `SidebarCollapse.test.tsx` — jsdom ne l'implémente pas. */
function stubMatchMedia(narrow: boolean): void {
  vi.stubGlobal(
    'matchMedia',
    (query: string) =>
      ({
        matches: narrow && query.includes('max-width'),
        media: query,
        onchange: null,
        addEventListener: () => {},
        removeEventListener: () => {},
        addListener: () => {},
        removeListener: () => {},
        dispatchEvent: () => false,
      }) as unknown as MediaQueryList,
  )
}

beforeEach(() => {
  localStorage.clear()
  stubMatchMedia(false)
})

describe('#2435.9 — capture photo directe depuis le composeur mobile', () => {
  it('sur téléphone, le menu « + » propose « Prendre une photo », qui ouvre un input caméra dédié', async () => {
    stubMatchMedia(true)
    const user = userEvent.setup({ pointerEventsCheck: 0 })
    const { container } = render(<Chat />)

    await user.click(screen.getByLabelText('Ajouter à ce message'))

    const cameraItem = await screen.findByText('Prendre une photo')
    expect(cameraItem).toBeInTheDocument()

    const cameraInput = container.querySelector('input[type="file"][capture]')
    expect(cameraInput).not.toBeNull()
    expect(cameraInput?.getAttribute('capture')).toBe('environment')
    expect(cameraInput?.getAttribute('accept')).toBe('image/*')
  })

  it('sur bureau, aucune entrée « Prendre une photo » — la capture caméra ne concerne que le mobile', async () => {
    stubMatchMedia(false)
    const user = userEvent.setup({ pointerEventsCheck: 0 })
    render(<Chat />)

    await user.click(screen.getByLabelText('Ajouter à ce message'))

    expect(screen.queryByText('Prendre une photo')).not.toBeInTheDocument()
  })
})
