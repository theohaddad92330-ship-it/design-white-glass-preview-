async function send(text: string) {
  await waitFor(() => expect(listMessagesMock).toHaveBeenCalled())
  const textarea = screen.getByPlaceholderText('Écris ton message...')
  fireEvent.change(textarea, { target: { value: text } })
  fireEvent.keyDown(textarea, { key: 'Enter' })
}

describe('#2450.1 / #2448.1 — le sélecteur de mode de recherche sur /chat', () => {
  it('un sélecteur « Mode de recherche » est monté sous la saisie', async () => {
    render(<Chat />)
    expect(await screen.findByRole('combobox', { name: /mode de recherche/i })).toBeInTheDocument()
  })

  it('par défaut « auto », envoyé tel quel avec le tour', async () => {
    render(<Chat />)
    await send('Bonjour')
    await waitFor(() =>
      expect(askLauraStreamingMock).toHaveBeenLastCalledWith(
        expect.objectContaining({ message: 'Bonjour', mode: 'auto' }),
        expect.anything(),
        expect.anything(),
      ),
    )
  })

  it('choisir « Approfondi » force le mode du tour suivant', async () => {
    render(<Chat />)
    await waitFor(() => expect(listMessagesMock).toHaveBeenCalled())

    await chooseOption(screen.getByRole('combobox', { name: /mode de recherche/i }), 'approfondi')

    await send('Et maintenant ?')
    await waitFor(() =>
      expect(askLauraStreamingMock).toHaveBeenLastCalledWith(
        expect.objectContaining({ message: 'Et maintenant ?', mode: 'approfondi' }),
        expect.anything(),
        expect.anything(),
      ),
    )
  })
})
