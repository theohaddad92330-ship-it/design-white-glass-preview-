import { z } from 'zod'

export type BellumEvent<EventType extends string = string, EventPayload = unknown> = {
  type: EventType
} & EventPayload

// ── Envelope ─────────────────────────────────────────────────────────────────
//
// Every domain event carries the same envelope (eventId, occurredAt,
// correlationId) so consumers can reason about ordering, retries and
// distributed traces without re-inventing the wheel per event type.
//
// `eventId` is the idempotency key — Redis Streams gives at-least-once
// delivery, so consumers that have side effects MUST track the eventIds
// they have already processed (see the audit consumer for an example).

const envelopeFields = {
  eventId: z.string().guid(),
  occurredAt: z.string().datetime(), // ISO 8601, generated by the publisher
  correlationId: z.string().min(1).optional(),
}

// ── Per-event payloads ───────────────────────────────────────────────────────

export const analysisStartedSchema = z.object({
  type: z.literal('analysis.started'),
  ...envelopeFields,
  jobId: z.string().min(1),
  accountId: z.string().guid(),
  userId: z.string().guid(),
  companyName: z.string().min(1),
})

export const analysisPhaseCompletedSchema = z.object({
  type: z.literal('analysis.phase_completed'),
  ...envelopeFields,
  jobId: z.string().min(1),
  accountId: z.string().guid(),
  phase: z.enum(['research', 'contacts', 'classify', 'plan']),
  /** Server-side percent at the point of phase completion (matches the
   *  values emitted on the WS gateway). */
  percent: z.number().int().min(0).max(100),
})

export const analysisCompletedSchema = z.object({
  type: z.literal('analysis.completed'),
  ...envelopeFields,
  jobId: z.string().min(1),
  accountId: z.string().guid(),
  userId: z.string().guid(),
  durationMs: z.number().int().nonnegative(),
})

export const analysisFailedSchema = z.object({
  type: z.literal('analysis.failed'),
  ...envelopeFields,
  jobId: z.string().min(1),
  accountId: z.string().guid(),
  userId: z.string().guid(),
  /** Stable code from the IA payload (FIRECRAWL_*, CLAUDE_*) when known,
   *  ``UNKNOWN`` otherwise — drives ops dashboards / alerts. */
  errorCode: z.string().min(1),
  /** French sentence the user actually saw (or "" if there was no
   *  user_message in the IA payload). */
  userMessage: z.string(),
})

export const contactEnrichedSchema = z.object({
  type: z.literal('contact.enriched'),
  ...envelopeFields,
  contactId: z.string().guid(),
  accountId: z.string().guid(),
  userId: z.string().guid(),
  source: z.string().min(1),
  /** Did Apollo find an email/phone? Lets analytics distinguish "ran but
   *  empty" from "ran and matched". */
  matched: z.boolean(),
})

export const accountDeletedSchema = z.object({
  type: z.literal('account.deleted'),
  ...envelopeFields,
  accountId: z.string().guid(),
  userId: z.string().guid(),
  /** True when an in-flight BullMQ job was cancelled at the same time —
   *  ops can correlate this with a corresponding ``analysis.failed``
   *  event for the same accountId. */
  hadActiveJob: z.boolean(),
})

// ── Discriminated union ──────────────────────────────────────────────────────

export const DomainEventSchema = z.discriminatedUnion('type', [
  analysisStartedSchema,
  analysisPhaseCompletedSchema,
  analysisCompletedSchema,
  analysisFailedSchema,
  contactEnrichedSchema,
  accountDeletedSchema,
])

export type DomainEvent = z.infer<typeof DomainEventSchema>
export type DomainEventType = DomainEvent['type']

// ── Stream routing ──────────────────────────────────────────────────────────
//
// One Redis Stream per event type. Trade-off: we lose global ordering
// across types (e.g. `account.deleted` and `analysis.failed` may interleave)
// but consumers can subscribe to a subset cheaply, and ``XLEN`` per stream
// is meaningful for ops. Switching to a single ``bellum:events:domain``
// stream later is non-breaking — we'd just route every type there.

export const STREAM_PREFIX = 'bellum:events:'

export const STREAM_BY_TYPE: Record<DomainEventType, string> = {
  'analysis.started': `${STREAM_PREFIX}analysis.started`,
  'analysis.phase_completed': `${STREAM_PREFIX}analysis.phase_completed`,
  'analysis.completed': `${STREAM_PREFIX}analysis.completed`,
  'analysis.failed': `${STREAM_PREFIX}analysis.failed`,
  'contact.enriched': `${STREAM_PREFIX}contact.enriched`,
  'account.deleted': `${STREAM_PREFIX}account.deleted`,
}

export const ALL_STREAMS: string[] = Object.values(STREAM_BY_TYPE)
