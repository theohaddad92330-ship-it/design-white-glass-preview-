function seedToRule(seed: Seed, sourceDocument: string): MethodRule {
  const [id, category, domain, stage, title, recommendation, sourceSection, sourcePage] = seed
  const defaults = CATEGORY_DEFAULTS[category]
  return {
    rule_id: id,
    title,
    category,
    domain,
    source_document: `${sourceDocument} — ${sourceSection}`,
    source_page: sourcePage,
    version: SALESCONNECT_CORPUS_VERSION,
    status: category === 'superseded' ? 'deprecated' : 'active',
    trigger: `${stage} ${triggerSlug(title)}`,
    applicable_roles: [],
    applicable_stages: [stage],
    applicable_sectors: [],
    applicable_channels: CHANNELS_BY_RULE_ID[id] ?? [],
    prerequisites: [],
    recommendation,
    exceptions: [],
    counter_example: null,
    stop_condition: null,
    evidence_required: defaults.evidenceRequired,
    confidence: defaults.confidence,
    user_override_allowed: defaults.userOverrideAllowed,
    telemetry_required: defaults.telemetryRequired,
  }
}

function seedToGovernance(seed: Seed, featureFlagKey: string): MethodRuleGovernance {
  const [id, category] = seed
  const enabled = category !== 'superseded'
  return {
    rule_id: id,
    owner: 'produit',
    feature_flag_key: featureFlagKey,
    enabled,
    disabled_reason: enabled
      ? null
      : 'SUPERSEDED (SC-CORPUS, #3250) : contredit la doctrine produit actuelle — JAMAIS de donnée fictive.',
    comparison_to_product_rules: category === 'superseded' ? 'superseded' : 'keep',
    impact_metric_key: null,
  }
}

