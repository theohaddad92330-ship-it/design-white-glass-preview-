type Seed = readonly [
  id: string,
  category: MethodRuleCategory,
  domain: MethodRuleDomain,
  stage: SalesConnectCycleStage,
  title: string,
  recommendation: string,
  sourceSection: string,
  sourcePage: number | null,
]

const CATEGORY_DEFAULTS: Record<
  MethodRuleCategory,
  {
    readonly confidence: MethodRule['confidence']
    readonly evidenceRequired: boolean
    readonly userOverrideAllowed: boolean
    readonly telemetryRequired: boolean
  }
> = {
  invariant: { confidence: 'high', evidenceRequired: true, userOverrideAllowed: false, telemetryRequired: true },
  adaptive_policy: {
    confidence: 'medium',
    evidenceRequired: false,
    userOverrideAllowed: true,
    telemetryRequired: true,
  },
  playbook: { confidence: 'medium', evidenceRequired: false, userOverrideAllowed: true, telemetryRequired: true },
  case_study: { confidence: 'medium', evidenceRequired: false, userOverrideAllowed: true, telemetryRequired: false },
  commercial_claim: { confidence: 'low', evidenceRequired: true, userOverrideAllowed: true, telemetryRequired: true },
  superseded: { confidence: 'high', evidenceRequired: false, userOverrideAllowed: false, telemetryRequired: false },
}

/** minuscules, sans accents, ponctuation retirée — même discipline que
 *  `ingestion-guard.ts` (`normalize`), pour un trigger stable et comparable. */
function triggerSlug(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .join(' ')
}

